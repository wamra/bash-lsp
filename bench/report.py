import json, sys

CATEGORIES = ["definition", "references", "scope", "source resolution", "dynamic edges", "call hierarchy",
              "symbols and hover", "error recovery", "diagnostics", "rename", "editor features"]


def suite_doc(result_file, triage_file, truth_hash, result_hash):
    """docs/benchmark.md from a suite result file plus the triage of its failures.

    Usage (from the repository root):
      uv run --no-project python bench/report.py --suite bench/results/suite-bash-lsp-m4.json \
          bench/suite_triage.json TRUTH_HASH RESULT_HASH > docs/benchmark.md
    """
    r = json.load(open(result_file))
    tri = json.load(open(triage_file))
    res = r["results"]
    orig = {k: v for k, v in res.items() if k.startswith("C")}
    suite = {k: v for k, v in res.items() if k.startswith("S")}
    failing = sorted(k for k, v in suite.items() if not v["pass"])
    missing = [k for k in failing if k not in tri]
    if missing:
        sys.exit("failing cases without triage: %s" % missing)
    stale = [k for k in tri if k not in failing]
    if stale:
        sys.exit("triage entries for cases that do not fail: %s" % stale)
    unknown = sorted({v["category"] for v in suite.values()} - set(CATEGORIES))
    if unknown:
        sys.exit("unknown categories: %s" % unknown)

    def cnt(cat, tier):
        xs = [v for v in suite.values() if v["category"] == cat and v["tier"] == tier]
        return sum(v["pass"] for v in xs), len(xs)

    def cell(p):
        return "-" if p[1] == 0 else "%d / %d" % p
    out = []
    w = out.append
    w("# Benchmark: the truth-file suite\n")
    w("Server: %s. Truth files committed in `%s`; result file `bench/results/%s` committed in `%s`.\n"
      % (r["name"], truth_hash, result_file.split("/")[-1], result_hash))
    w("This file is generated by `bench/report.py --suite` from the result file; do not edit it by hand.\n")
    w("## Limits\n")
    w("- The corpus (`bench/testdata/corpus2`) and every expectation were written by an agent, from the bash manual "
      "and the LSP 3.17 typings, before any server output was seen. No human has audited them.")
    w("- One machine, macOS only. Linux and Windows are not measured.")
    w("- bash-lsp only. The competing servers are not run on this suite yet (Task 14), and the `bash -n` and "
      "`bash-trace` oracles are cross-checked only in Task 14.")
    w("- The server runs with shellcheck disabled (`bench/config-shellcheck-off.toml`), so diagnostics are the native ones.")
    w("- Each case runs on a fresh server over a fresh copy of the corpus; the file is opened and the harness waits 2 s "
      "before asking. Latency-sensitive failures were re-run with 6 s and stayed failing.")
    w("- Case expectations were frozen before the first result; none was edited afterwards. Gating cases are the "
      "contract, design cases (soft design assumptions) are reported separately.\n")
    w("## Results per category\n")
    w("Passed / total.\n")
    w("| Category | Gating | Design |")
    w("|---|---|---|")
    tg = [0, 0]
    td = [0, 0]
    for c in CATEGORIES:
        g, d = cnt(c, "gating"), cnt(c, "design")
        tg[0] += g[0]; tg[1] += g[1]; td[0] += d[0]; td[1] += d[1]
        w("| %s | %s | %s |" % (c, cell(g), cell(d)))
    w("| **Total** | **%d / %d** | **%d / %d** |\n" % (tg[0], tg[1], td[0], td[1]))
    w("The 28 original cases (`bench.py`): %d / %d.\n" % (sum(v[0] for v in orig.values()), len(orig)))
    w("## Failing cases\n")
    w("| Case | Tier | Category | Class | Owner | Smallest fix or note |")
    w("|---|---|---|---|---|---|")
    for k in failing:
        t = tri[k]
        w("| %s | %s | %s | %s | %s | %s |" % (k, suite[k]["tier"], suite[k]["category"], t["class"], t["owner"], t["fix"]))
    w("")
    return "\n".join(out)


if "--suite" in sys.argv:
    a = sys.argv[sys.argv.index("--suite") + 1:]
    print(suite_doc(a[0], a[1], a[2], a[3]))
    sys.exit(0)

